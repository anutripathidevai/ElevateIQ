/**
 * Generate a single, paste-ready SQL file for Neon's SQL Editor (or any psql):
 *   1) the Prisma migration DDL (schema), then
 *   2) idempotent INSERTs for the problem bank from content/*.json.
 *
 * This lets you set up the database entirely from the Neon web console without
 * running `prisma migrate deploy` / `npm run db:seed` locally.
 *
 * Usage:
 *   node scripts/azure/gen-neon-seed.mjs > neon-setup.sql
 *   node scripts/azure/gen-neon-seed.mjs path\to\neon-setup.sql
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const migrationsDir = join(repoRoot, "prisma", "migrations");
const contentDir = join(repoRoot, "content");

// Migrations in apply order (matches prisma/migrations/ names).
const MIGRATIONS = ["0_init", "20260714_phase2_career_modules"];
const SOURCES = [
  { file: "dsa.json", track: "DSA" },
  { file: "system-design.json", track: "SYSTEM_DESIGN" },
  { file: "lld.json", track: "LLD" },
  { file: "behavioral.json", track: "BEHAVIORAL" },
];

/** Dollar-quote a string with a tag guaranteed not to appear inside it. */
function dq(value) {
  if (value === null || value === undefined) return "NULL";
  const s = String(value);
  let i = 0;
  let tag = "$q$";
  while (s.includes(tag)) tag = `$q${++i}$`;
  return `${tag}${s}${tag}`;
}

/** Postgres text[] array literal. */
function arr(list) {
  if (!list || list.length === 0) return "ARRAY[]::text[]";
  return `ARRAY[${list.map(dq).join(",")}]::text[]`;
}

/** jsonb literal or NULL. */
function jsonb(obj) {
  if (obj === null || obj === undefined) return "NULL";
  return `${dq(JSON.stringify(obj))}::jsonb`;
}

const out = [];
out.push("-- ElevateIQ — Neon setup (generated by scripts/azure/gen-neon-seed.mjs)");
out.push("-- Paste into Neon SQL Editor. SCHEMA runs once; DATA is idempotent.\n");

out.push("-- ============ SCHEMA (run once) ============");
for (const name of MIGRATIONS) {
  const sql = readFileSync(join(migrationsDir, name, "migration.sql"), "utf8");
  out.push(`-- >>> migration: ${name}`);
  out.push(sql.trim());
  out.push("");
}

out.push("-- ============ DATA (idempotent upsert by slug) ============");
out.push("BEGIN;");
const cols = [
  "id", "track", "slug", "title", "difficulty", "tags",
  "statementMD", "constraints", "hints", "referenceSolution", "judgeSpec", "solution",
];
const colList = cols.map((c) => `"${c}"`).join(", ");
const updateList = cols
  .filter((c) => c !== "id" && c !== "slug")
  .map((c) => `"${c}"=EXCLUDED."${c}"`)
  .join(", ");

let total = 0;
for (const { file, track } of SOURCES) {
  const items = JSON.parse(readFileSync(join(contentDir, file), "utf8"));
  out.push(`-- ${track} (${items.length}) from ${file}`);
  for (const p of items) {
    const values = [
      "gen_random_uuid()::text",
      `'${track}'::"TrackKey"`,
      dq(p.slug),
      dq(p.title),
      `${dq(p.difficulty)}::"Difficulty"`,
      arr(p.tags ?? []),
      dq(p.statementMD),
      dq(p.constraints ?? null),
      arr(p.hints ?? []),
      dq(p.referenceSolution ?? null),
      jsonb(p.judge ?? null),
      jsonb(p.solution ?? null),
    ].join(", ");
    out.push(
      `INSERT INTO "Problem" (${colList}) VALUES (${values})\n` +
        `ON CONFLICT ("slug") DO UPDATE SET ${updateList};`,
    );
    total++;
  }
  out.push("");
}
out.push("COMMIT;");
out.push(`-- Seeded ${total} problems.`);

const sqlText = out.join("\n") + "\n";
const target = process.argv[2];
if (target) {
  writeFileSync(target, sqlText, "utf8");
  console.error(`Wrote ${total} problems + schema to ${target}`);
} else {
  process.stdout.write(sqlText);
}
